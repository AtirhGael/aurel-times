declare(strict_types=1);
require __DIR__ . '/_guard.php';

$pdo = db();

function scalar(PDO $pdo, string $sql, array $args = []): float
{
    try {
        $st = $pdo->prepare($sql);
        $st->execute($args);
        return (float)$st->fetchColumn();
    } catch (Throwable $e) {
        return 0.0;
    }
}

$counts = [
    'orders'   => (int)scalar($pdo, 'SELECT COUNT(*) FROM orders'),
    'products' => (int)scalar($pdo, 'SELECT COUNT(*) FROM products'),
    'users'    => (int)scalar($pdo, 'SELECT COUNT(*) FROM users'),
    'unread'   => (int)scalar($pdo, 'SELECT COUNT(*) FROM contact_messages WHERE is_read = 0'),
    'reviews'  => (int)scalar($pdo, 'SELECT COUNT(*) FROM reviews'),
];
$revenueAll  = scalar($pdo, "SELECT COALESCE(SUM(total),0) FROM orders WHERE status NOT IN ('cancelled','refunded')");
$revenue7d   = scalar($pdo, "SELECT COALESCE(SUM(total),0) FROM orders
                             WHERE status NOT IN ('cancelled','refunded') AND created_at >= NOW() - INTERVAL 7 DAY");
$openOrders  = (int)scalar($pdo, "SELECT COUNT(*) FROM orders WHERE status IN ('pending','paid','processing')");

try {
    $recent = $pdo->query(
        'SELECT id, full_name, email, total, status, created_at FROM orders ORDER BY id DESC LIMIT 8'
    )->fetchAll();
} catch (Throwable $e) {
    $recent = [];
}

/* ---- Pre-launch checklist ------------------------------------------------ */
$stale  = placeholder_settings();
$checks = [];

$checks[] = [
    'ok'    => empty($stale),
    'label' => 'Real business contact details',
    'detail' => $stale
        ? count($stale) . ' field(s) still hold shipped placeholder values: '
          . implode(', ', array_map(static fn($s) => $s['label'], $stale))
        : 'Address, phone and email have all been replaced with real values.',
    'link'  => admin_url('settings.php#grp-contact'),
    'cta'   => 'Edit contact settings',
];

$socialCount = count(setting_social_links());
$checks[] = [
    'ok'     => true,
    'soft'   => $socialCount === 0,
    'label'  => 'Social profiles',
    'detail' => $socialCount > 0
        ? $socialCount . ' profile link(s) configured.'
        : 'None set. That is fine — an empty list is honest. Only add links to profiles that actually exist.',
    'link'   => admin_url('settings.php#grp-social'),
    'cta'    => 'Add profiles',
];

$pageCount = count(all_pages(true));
$checks[] = [
    'ok'     => $pageCount >= 7,
    'label'  => 'Policy pages published',
    'detail' => $pageCount . ' page(s) published. Shipping, returns, refunds, privacy and terms should all be live '
              . 'and should describe what you actually do.',
    'link'   => admin_url('pages.php'),
    'cta'    => 'Review pages',
];

$fakeCompare = (int)scalar($pdo, 'SELECT COUNT(*) FROM products WHERE compare_at_price IS NOT NULL AND compare_at_price <= base_price');
$checks[] = [
    'ok'     => $fakeCompare === 0,
    'label'  => 'No invented reference prices',
    'detail' => $fakeCompare === 0
        ? 'Strikethrough "was" prices only appear where a genuine compare-at price is stored.'
        : $fakeCompare . ' product(s) have a compare-at price at or below the selling price.',
    'link'   => null,
];

$checks[] = [
    'ok'     => $counts['reviews'] === 0,
    'label'  => 'No machine-generated reviews',
    'detail' => $counts['reviews'] === 0
        ? 'No reviews stored. Star ratings and AggregateRating markup stay hidden until real customers write them.'
        : $counts['reviews'] . ' review(s) stored. If any were generated by setup.php --demo-reviews, delete them: '
          . 'presenting synthetic text as customer reviews breaches the FTC\'s 2024 rule and carries civil penalties.',
    'link'   => admin_url('reviews.php'),
    'cta'    => 'Manage reviews',
];

$indexOn = setting_bool('robots_index');
$blockers = count(array_filter($checks, static fn($c) => empty($c['ok'])));
$checks[] = [
    'ok'     => $indexOn && $blockers === 0,
    'soft'   => !$indexOn,
    'label'  => 'Search engine indexing',
    'detail' => $indexOn
        ? ($blockers === 0
            ? 'Indexing is on and every check above passes.'
            : 'Indexing is ON while ' . $blockers . ' check(s) still fail. Google may crawl placeholder details.')
        : 'Indexing is off (noindex). Turn it on once the checks above pass.',
    'link'   => admin_url('settings.php#grp-seo'),
    'cta'    => 'SEO settings',
];

