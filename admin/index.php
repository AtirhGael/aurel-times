      <div class="hd">
        Pre-launch checklist
        <?php if ($blockers > 0): ?>
          <span class="badge text-bg-warning ms-auto"><?= $blockers ?> to fix</span>
        <?php else: ?>
          <span class="badge text-bg-success ms-auto">All clear</span>
        <?php endif; ?>
      </div>
      <div class="bd">
        <p class="text-muted small">
          These are the things that make a store look real to a customer — and to Google.
          Work through them before you take live orders.
        </p>
        <?php foreach ($checks as $c): ?>
          <?php
            $state = !empty($c['ok']) ? 'ok' : (!empty($c['soft']) ? 'soft' : 'bad');
