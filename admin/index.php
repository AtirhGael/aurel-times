            <div style="color:<?= $color ?>;font-weight:700;font-size:1.05rem;width:16px"><?= $icon ?></div>
            <div class="flex-grow-1">
              <div style="font-weight:600;font-size:.92rem;color:<?= $state === 'bad' ? '#c8102e' : 'inherit' ?>">
                <?= h($c['label']) ?>
              </div>
              <div class="small text-muted"><?= h($c['detail']) ?></div>
              <?php if (!empty($c['link']) && $state !== 'ok'): ?>
                <a class="small" href="<?= h($c['link']) ?>"><?= h($c['cta'] ?? 'Fix this') ?> →</a>
              <?php endif; ?>
            </div>
          </div>
        <?php endforeach; ?>
      </div>
    </section>
  </div>

  <div class="col-lg-5">
    <section class="card-a mb-4">
      <div class="hd">Recent orders <a class="ms-auto small fw-normal" href="<?= admin_url('orders.php') ?>">View all</a></div>
      <div class="bd p-0">
        <?php if (!$recent): ?>
          <p class="text-muted small p-3 mb-0">No orders yet.</p>
        <?php else: ?>
          <table class="table table-sm">
            <thead><tr><th class="ps-3">#</th><th>Customer</th><th>Status</th><th class="text-end pe-3">Total</th></tr></thead>
            <tbody>
              <?php foreach ($recent as $o): ?>
                <tr>
                  <td class="ps-3"><a href="<?= admin_url('order.php?id=' . (int)$o['id']) ?>"><?= (int)$o['id'] ?></a></td>
                  <td><?= h(mb_strimwidth((string)$o['full_name'], 0, 22, '…')) ?></td>
                  <td><span class="badge text-bg-<?= h(order_status_class((string)$o['status'])) ?>"><?= h(order_status_label((string)$o['status'])) ?></span></td>
                  <td class="text-end pe-3"><?= h(money($o['total'])) ?></td>
                </tr>
              <?php endforeach; ?>
            </tbody>
          </table>
        <?php endif; ?>
      </div>
    </section>

    <section class="card-a">
      <div class="hd">Catalog</div>
      <div class="bd">
        <div class="d-flex justify-content-between small py-1"><span class="text-muted">Products</span><strong><?= number_format($counts['products']) ?></strong></div>
        <div class="d-flex justify-content-between small py-1"><span class="text-muted">Registered customers</span><strong><?= number_format($counts['users']) ?></strong></div>
        <div class="d-flex justify-content-between small py-1"><span class="text-muted">Orders</span><strong><?= number_format($counts['orders']) ?></strong></div>
        <div class="d-flex justify-content-between small py-1"><span class="text-muted">Reviews</span><strong><?= number_format($counts['reviews']) ?></strong></div>
      </div>
    </section>
  </div>
</div>

